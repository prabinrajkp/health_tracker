// Turns the Lucide icons the app uses into Android vector drawables for the
// home-screen widgets, so both draw the same icon set (Lucide is ISC licensed).
// Icons are white; each widget tints them with its own colours.
// Run by build_apk.sh before every build, or with `npm run widgets:res`.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root  = join(dirname(fileURLToPath(import.meta.url)), '..')
const icons = join(root, 'node_modules/lucide-react/dist/esm/icons')
const out   = join(root, 'android/app/src/main/res/drawable')

// Lucide name → drawable name (w_ic_*)
const ICONS = {
  'utensils': 'meal', 'footprints': 'steps', 'moon': 'sleep', 'scale': 'weight',
  'play': 'play', 'square': 'stop',
  'plus': 'plus', 'minus': 'minus', 'undo-2': 'undo', 'thermometer': 'sick', 'check': 'check',
  'chevron-right': 'chevron', 'flame': 'streak', 'circle': 'circle',
}

function iconNode(name) {
  const src = readFileSync(join(icons, `${name}.js`), 'utf8')
  const start = src.indexOf('[', src.indexOf('createLucideIcon('))
  const end = src.lastIndexOf(']);')
  // The node list is a plain array literal of [tag, attributes] pairs
  return new Function(`return ${src.slice(start, end + 1)}`)()
}

const n = (v) => Number(v)
function toPath(tag, a) {
  switch (tag) {
    case 'path': return a.d
    case 'line': return `M${a.x1} ${a.y1}L${a.x2} ${a.y2}`
    case 'polyline':
    case 'polygon': {
      const pts = a.points.trim().split(/[\s,]+/).map(Number)
      let d = `M${pts[0]} ${pts[1]}`
      for (let i = 2; i < pts.length; i += 2) d += `L${pts[i]} ${pts[i + 1]}`
      return tag === 'polygon' ? `${d}Z` : d
    }
    case 'circle': {
      const [cx, cy, r] = [n(a.cx), n(a.cy), n(a.r)]
      return `M${cx - r} ${cy}a${r} ${r} 0 1 0 ${2 * r} 0a${r} ${r} 0 1 0 ${-2 * r} 0`
    }
    case 'ellipse': {
      const [cx, cy, rx, ry] = [n(a.cx), n(a.cy), n(a.rx), n(a.ry)]
      return `M${cx - rx} ${cy}a${rx} ${ry} 0 1 0 ${2 * rx} 0a${rx} ${ry} 0 1 0 ${-2 * rx} 0`
    }
    case 'rect': {
      const [x, y, w, h] = [n(a.x || 0), n(a.y || 0), n(a.width), n(a.height)]
      const r = Math.min(n(a.rx ?? a.ry ?? 0), w / 2, h / 2)
      if (!r) return `M${x} ${y}h${w}v${h}h${-w}Z`
      return `M${x + r} ${y}h${w - 2 * r}a${r} ${r} 0 0 1 ${r} ${r}v${h - 2 * r}a${r} ${r} 0 0 1 ${-r} ${r}` +
        `h${-(w - 2 * r)}a${r} ${r} 0 0 1 ${-r} ${-r}v${-(h - 2 * r)}a${r} ${r} 0 0 1 ${r} ${-r}Z`
    }
    default: throw new Error(`Unsupported SVG element <${tag}>`)
  }
}

const HEADER = '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by scripts/gen_widget_icons.mjs from Lucide (ISC licence). Do not edit by hand. -->\n'

mkdirSync(out, { recursive: true })
for (const [lucide, name] of Object.entries(ICONS)) {
  const paths = iconNode(lucide).map(([tag, attrs]) =>
    `    <path android:pathData="${toPath(tag, attrs)}"\n        android:fillColor="#00000000" android:strokeColor="#FFFFFFFF" android:strokeWidth="2"\n        android:strokeLineCap="round" android:strokeLineJoin="round" />\n`).join('')
  writeFileSync(join(out, `w_ic_${name}.xml`), `${HEADER}<vector xmlns:android="http://schemas.android.com/apk/res/android"\n    android:width="24dp" android:height="24dp" android:viewportWidth="24" android:viewportHeight="24">\n${paths}</vector>\n`)
}
console.log(`Widget icons: ${Object.keys(ICONS).length} from Lucide`)
