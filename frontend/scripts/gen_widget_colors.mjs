// Generates the home-screen widget colours from the app's own theme tokens in
// src/index.css, so a change to the app's theme reaches the widgets by itself.
// Run by build_apk.sh before every build, or with `npm run widgets:res`.
//
// Writes res/values/widget_colors.xml (light, plus both sets by name) and
// res/values-night/widget_colors.xml (dark). Fails if a token is missing or a
// text colour falls under 4.5:1 on the surfaces it is used on.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const css  = readFileSync(join(root, 'src/index.css'), 'utf8')
const res  = join(root, 'android/app/src/main/res')

// Widget colour name → app token. One list, so the widgets use only what the app uses.
const ROLES = {
  card:     'surface-card',
  tile:     'surface-elevated',
  border:   'surface-border',
  edge:     'surface-muted',
  text:     'text-primary',
  text2:    'text-secondary',
  muted:    'text-muted',
  brand:    'brand',
  on_brand: 'on-brand',
  success:  'success',
  warning:  'warning',
  danger:   'danger',
  water:    'water',
  diet:     'cat-diet',
  fasting:  'cat-fasting',
  workout:  'cat-workout',
  sleep:    'cat-sleep',
}
// The grade chip and status tints: the tone at 14% behind its own colour, as on Today
const TINTS = { brand: 0.14, success: 0.14, warning: 0.14, danger: 0.14 }

function block(selector) {
  const start = css.indexOf(`${selector} {`)
  if (start < 0) throw new Error(`No "${selector}" block in index.css`)
  return css.slice(start, css.indexOf('}', start))
}

function tokens(selector) {
  const out = {}
  for (const m of block(selector).matchAll(/--c-([a-z-]+):\s*(\d+)\s+(\d+)\s+(\d+)\s*;/g)) {
    out[m[1]] = [Number(m[2]), Number(m[3]), Number(m[4])]
  }
  return out
}

const themes = { dark: tokens(':root'), light: tokens('.light') }
const hex2 = (n) => n.toString(16).padStart(2, '0').toUpperCase()
const argb = ([r, g, b], a = 1) => `#${hex2(Math.round(a * 255))}${hex2(r)}${hex2(g)}${hex2(b)}`

const colours = {}
for (const [mode, t] of Object.entries(themes)) {
  const c = {}
  for (const [role, token] of Object.entries(ROLES)) {
    if (!t[token]) throw new Error(`Token --c-${token} is missing from the ${mode} theme in index.css`)
    c[role] = argb(t[token])
  }
  for (const [role, alpha] of Object.entries(TINTS)) c[`${role}_tint`] = argb(t[ROLES[role]], alpha)
  // Light mode separates cards with a border; dark mode by brightness alone, as in the app
  if (mode === 'dark') c.border = '#00000000'
  colours[mode] = c
}

// ── Contrast: the same bar the app sets for itself (docs/ui_critic.md) ────────
const lum = ([r, g, b]) => {
  const ch = (v) => { v /= 255; return v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4 }
  return 0.2126 * ch(r) + 0.7152 * ch(g) + 0.0722 * ch(b)
}
const ratio = (a, b) => { const [x, y] = [lum(a), lum(b)].sort((p, q) => q - p); return (x + 0.05) / (y + 0.05) }
const over = (fg, bg, a) => fg.map((v, i) => Math.round(v * a + bg[i] * (1 - a)))

const failures = []
for (const [mode, t] of Object.entries(themes)) {
  const check = (label, fg, bg) => {
    const r = ratio(fg, bg)
    if (r < 4.5) failures.push(`${mode}: ${label} is ${r.toFixed(2)}:1`)
  }
  for (const text of ['text-primary', 'text-secondary', 'text-muted', 'brand', 'success', 'warning', 'danger']) {
    check(`${text} on card`, t[text], t['surface-card'])
    check(`${text} on tile`, t[text], t['surface-elevated'])
  }
  check('on-brand on brand', t['on-brand'], t.brand)
  for (const tone of Object.keys(TINTS)) {
    check(`${tone} on its chip`, t[ROLES[tone]], over(t[ROLES[tone]], t['surface-card'], TINTS[tone]))
  }
}
if (failures.length) {
  console.error('Widget colours fail the 4.5:1 contrast check:\n  ' + failures.join('\n  '))
  process.exit(1)
}

// ── Write ─────────────────────────────────────────────────────────────────────
const HEADER = '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by scripts/gen_widget_colors.mjs from src/index.css. Do not edit by hand. -->\n<resources>\n'
const line = (name, value) => `    <color name="${name}">${value}</color>\n`
const names = Object.keys(colours.dark)

let day = HEADER
for (const mode of ['light', 'dark']) for (const n of names) day += line(`hq_${mode}_${n}`, colours[mode][n])
for (const n of names) day += line(`widget_${n}`, `@color/hq_light_${n}`)
day += '</resources>\n'

let night = HEADER
for (const n of names) night += line(`widget_${n}`, `@color/hq_dark_${n}`)
night += '</resources>\n'

mkdirSync(join(res, 'values'), { recursive: true })
mkdirSync(join(res, 'values-night'), { recursive: true })
writeFileSync(join(res, 'values/widget_colors.xml'), day)
writeFileSync(join(res, 'values-night/widget_colors.xml'), night)
console.log(`Widget colours: ${names.length} roles, light and dark, from index.css`)
